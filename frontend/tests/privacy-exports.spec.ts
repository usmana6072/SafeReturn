import { test, expect as baseExpect } from "@playwright/test";
const expect = baseExpect.configure({ timeout: 20000 });
test("synthetic reviewed basic_v1 request, scoped decision, encrypted generation and one-use delivery", async ({ page, context, request }, testInfo) => {
  test.setTimeout(240000);
  page.setDefaultTimeout(20000);
  await page.goto("/account/privacy/exports"); await expect(page).toHaveURL(/login/);
  expect((await page.request.get("/account/privacy/exports/api?id=00000000-0000-0000-0000-000000000000")).status()).toBe(401);
  async function login(role: string) {
    await context.clearCookies();
    await request.post("http://127.0.0.1:8115/fixture/support-role/" + role);
    await page.goto("/login"); await page.getByLabel("Email address").fill(role + "@synthetic.invalid");
    await page.locator("input[name=password]").fill("synthetic-password");
    await page.getByRole("button", { name: "Log in", exact: true }).click();
    await expect(page).not.toHaveURL(/\/login/);
  }
  await login("a"); await page.goto("/account/privacy/exports");
  await expect(page.getByText(/not a complete legal account dump/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Request basic_v1 export" })).toBeDisabled();
  await page.getByRole("checkbox").check(); await page.getByRole("button", { name: "Request basic_v1 export" }).click();
  await expect(page.getByRole("status")).toHaveText("Request saved for review.");
  const id = await page.getByLabel("Request ID", { exact: true }).inputValue();
  await expect(page.getByRole("heading", { name: id, exact: true })).toBeVisible();
  expect((await page.request.post("/account/privacy/exports/api", { headers: { Origin: "https://bad.invalid" }, data: {} })).status()).toBe(403);
  expect((await page.request.get("/account/privacy/exports/api?path=/admin/privacy/exports")).status()).toBe(400);
  await login("b"); await page.goto("/account/privacy/exports"); await page.getByLabel("Request ID", { exact: true }).fill(id);
  await page.getByRole("button", { name: "Load status" }).click(); await expect(page.getByRole("status")).toHaveText("Request not found.");
  await login("support"); await page.goto("/admin/privacy/exports?view=live"); await expect(page.getByRole("heading", { name: "Access denied", exact: true })).toBeVisible();
  await request.post("http://127.0.0.1:8115/fixture/export-authorize");
  await login("security_admin"); await page.goto("/admin/privacy/exports?view=live"); await page.getByRole("button", { name: "Load status" }).click();
  await expect(page.getByRole("heading", { name: id, exact: true })).toBeVisible();
  await expect(page.locator("body")).not.toContainText("PRIVATE");
  await page.getByRole("checkbox").check(); await page.getByRole("button", { name: "Save review decision" }).click();
  await expect(page.getByRole("status")).toHaveText("Decision saved.");
  expect((await request.post("http://127.0.0.1:8115/fixture/export-build")).ok()).toBe(true);
  await login("a"); await page.goto("/account/privacy/exports"); await page.getByLabel("Request ID", { exact: true }).fill(id);
  await page.getByRole("button", { name: "Load status" }).click();
  await expect(page.getByRole("button", { name: "Download reviewed export" })).toBeVisible();
  await page.getByRole("checkbox").check();
  const waiting = page.waitForEvent("download"); await page.getByRole("button", { name: "Download reviewed export" }).click();
  const download = await waiting; expect(download.suggestedFilename()).toBe("safereturn-basic-v1.json");
  await download.saveAs(testInfo.outputPath("synthetic-basic-v1.json"));
  await expect(page.getByRole("status")).toHaveText("Export downloaded.");
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0]);
  await context.addCookies([{ name: "safereturn-language", value: "ur", url: "http://127.0.0.1:3100" }]);
  await page.setViewportSize({ width: 375, height: 900 }); await page.reload();
  await expect(page.locator("html")).toHaveAttribute("dir", "rtl");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("privacy-rtl.png"), fullPage: true });
});
